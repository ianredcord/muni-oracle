#!/usr/bin/env node
// 由 handoff/data/*.v2.json 與 src/data/MUNI_78Cards_Content_v4.1.json 產生 src/data/threeCard/*.ts。
//   node scripts/generate-three-card-data.mjs [--check]
// 不要手改產出的 .ts；改 JSON 後重跑本腳本。
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { buildCards } from "./generate-tarot.mjs";

const CHECK = process.argv.includes("--check");
const SRC = {
  cards: "src/data/MUNI_78Cards_Content_v4.1.json",
  meta: "src/data/tarot.meta.json",
  position: "handoff/data/position_text.v2.json",
  templates: "handoff/data/slot_templates_all.v2.json",
  mirror: "handoff/data/mirror_text.v2.json",
};
const OUT_DIR = "src/data/threeCard";

const read = (p) => JSON.parse(fs.readFileSync(p, "utf8"));
const MIRROR_OF = { major: "archetype", court: "persona", pip: "situation" };

export function buildThreeCardCards() {
  return buildCards(SRC.cards, SRC.meta).map((c) => {
    const isCourt = c.suit !== "major" && !c.number;
    const card = {
      id: c.id, slug: c.slug, nameZh: c.nameZh, nameEn: c.nameEn, suit: c.suit,
      ...(c.number ? { number: c.number } : {}),
      element: c.element, bachFlowerEn: c.bachFlowerEn, bachFlowerZh: c.bachFlowerZh,
      step2Allow: c.step2Allow, step3Body: c.step3Body, systemL2Echo: c.systemL2Echo,
      ...(isCourt ? { mbti: c.planetSign } : {}),
    };
    return card;
  });
}

function positionRows() {
  return read(SRC.position).map((r) => ({ cardId: r.card_id, position: r.position, text: r.text, status: r.status }));
}
function templateRows() {
  return read(SRC.templates); // 欄位已是 schema v2，原樣帶入
}
function mirrorRows(cards) {
  if (!fs.existsSync(SRC.mirror)) return [];
  const kindOf = (c) => (c.suit === "major" ? "major" : c.number ? "pip" : "court");
  const byId = new Map(cards.map((c) => [c.id, c]));
  return read(SRC.mirror).map((r) => {
    const c = byId.get(r.card_id);
    const mirror = r.mirror ?? MIRROR_OF[kindOf(c)];
    if (mirror !== MIRROR_OF[kindOf(c)]) throw new Error(`mirror 與牌種不符：card ${r.card_id} ${mirror}`);
    return { cardId: r.card_id, mirror, text: r.text, status: r.status };
  });
}

function file(name, typeName, constName, rows, sourceNote) {
  const body = JSON.stringify(rows, null, 2);
  return `// AUTO-GENERATED by scripts/generate-three-card-data.mjs — 來源：${sourceNote}
// 請勿手改；改 JSON 後重跑產生腳本。

import type { ${typeName} } from "../../lib/threeCard/types";

export const ${constName}: ${typeName}[] = ${body};
`;
}

export function renderAll() {
  const cards = buildThreeCardCards();
  return {
    "cards.ts": file("cards.ts", "Card", "THREE_CARD_CARDS", cards, path.basename(SRC.cards)),
    "positionText.ts": file("positionText.ts", "PositionText", "POSITION_TEXT", positionRows(), SRC.position),
    "slotTemplates.ts": file("slotTemplates.ts", "SlotTemplate", "SLOT_TEMPLATES", templateRows(), SRC.templates),
    "mirrorText.ts": file("mirrorText.ts", "MirrorText", "MIRROR_TEXT", mirrorRows(cards), `${SRC.mirror}（缺檔時為空陣列，引擎退回位置短文）`),
  };
}

if (import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  fs.mkdirSync(OUT_DIR, { recursive: true });
  let dirty = 0;
  for (const [name, content] of Object.entries(renderAll())) {
    const p = path.join(OUT_DIR, name);
    const cur = fs.existsSync(p) ? fs.readFileSync(p, "utf8") : null;
    if (cur === content) { console.log(`unchanged  ${p}`); continue; }
    dirty++;
    if (CHECK) console.log(`DIFF       ${p}`);
    else { fs.writeFileSync(p, content); console.log(`written    ${p}`); }
  }
  if (CHECK && dirty) process.exit(1);
}
